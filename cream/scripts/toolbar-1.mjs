import { chromium } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.setDefaultTimeout(15000);
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:5400/');
await p.waitForFunction(() => window.cream?.app.getState().ready);
const id = await p.evaluate(() => window.cream.app.getState().createDesign({ preset: 'instagram-square' }).id);
await p.goto('http://localhost:5400/#/design/' + id);
await p.waitForSelector('[data-testid=editor]');
await p.waitForTimeout(800);
const shot = async (n) => { await p.waitForTimeout(350); await p.screenshot({ path: `${out}/${n}.png` }); };
await shot('t0-page');
// text
await p.keyboard.press('t');
await p.waitForTimeout(400);
await p.waitForTimeout(200);
const st = await p.evaluate(() => ({ sel: window.cream.editor.getState().selection, ed: window.cream.editor.getState().editingId }));
console.log('after t', JSON.stringify(st));
await shot('t1-text');
await p.click('[data-testid=tb-bold]');
await p.click('[data-testid=tb-italic]');
await p.click('[data-testid=tb-case]');
await p.click('[data-testid=tb-align]');
await p.click('[data-testid=tb-font-size-inc]');
await shot('t2-text-formatted');
console.log(JSON.stringify(await p.evaluate(() => { const e = window.cream.editor.getState().design.pages[0].elements[0]; return { w: e.fontWeight, i: e.italic, u: e.uppercase, a: e.align, fs: e.fontSize }; })));
await p.click('[data-testid=tb-color]');
await shot('t3-color-panel');
await p.click('[data-testid=color-add]');
await shot('t4-color-custom');
await p.click('[data-testid=tb-font]');
await p.waitForTimeout(1500);
await shot('t5-font');
await p.click('[data-testid=tb-effects]');
await shot('t6-effects');
await p.click('[data-testid=effect-neon]');
await shot('t7-neon');
await p.click('[data-testid=tb-spacing]');
await shot('t8-spacing');
await p.click('[data-testid=tb-spacing]');
await p.click('[data-testid=tb-animate]');
await shot('t9-animate');
await p.click('[data-testid=tb-position]');
await shot('t10-position');
await p.click('[data-testid=tb-more]');
await shot('t11-more');
await p.keyboard.press('Escape');
console.log('ERRORS', JSON.stringify(errs.slice(0, 10)));
await b.close();
