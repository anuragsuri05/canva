// Extra checks: video insert, 3D see-all, graphics see-all, upload ⋯ menu → trash.
import { chromium } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const shot = async (n) => { await p.evaluate(() => document.querySelectorAll('vite-error-overlay').forEach((e) => e.remove())); await p.screenshot({ path: `${out}/${n}.png` }); };
const side = async (t) => { await p.evaluate((t) => window.cream.editor.setState({ side: t }), t); await p.waitForSelector(`[data-testid=panel-${t}]`); };
await p.goto('http://localhost:5400/');
await p.waitForFunction(() => window.cream?.app.getState().ready);
const id = await p.evaluate(() => window.cream.app.getState().createDesign({ preset: 'instagram-square' }).id);
await p.goto('http://localhost:5400/#/design/' + id);
await p.waitForSelector('[data-testid=editor]');
await p.waitForTimeout(1200);
await side('videos');
await p.waitForSelector('[data-testid=video-tile] img', { timeout: 20000 });
await p.locator('[data-testid=video-tile]').first().click();
await p.waitForFunction(() => window.cream.editor.getState().design.pages[0].elements.some((e) => e.type === 'video'), null, { timeout: 30000 });
console.log('video src', await p.evaluate(() => window.cream.editor.getState().design.pages[0].elements.find((e) => e.type === 'video').src));
await p.waitForTimeout(3000);
await shot('20-video-inserted');
await side('elements');
await p.click('[data-testid=see-all-3d]');
await p.waitForSelector('[data-testid=icon-tile]');
await p.waitForTimeout(2500);
await shot('21-3d');
await p.click('[data-testid=panel-back]');
await p.click('[data-testid=see-all-graphics]');
await p.waitForSelector('[data-testid=icon-tile]');
await p.waitForTimeout(2500);
await shot('22-graphics');
await p.click('[data-testid=panel-back]');
await p.click('[data-testid=see-all-photos]');
await p.waitForSelector('[data-testid=photo-tile] img', { timeout: 20000 });
await p.waitForTimeout(1500);
await shot('23-photos-all');
await side('uploads');
const buf = await p.screenshot({ clip: { x: 0, y: 0, width: 200, height: 200 } });
await p.setInputFiles('[data-testid=upload-input]', [{ name: 'a.png', mimeType: 'image/png', buffer: buf }]);
await p.waitForSelector('[data-testid=upload-tile]');
const n0 = await p.locator('[data-testid=upload-tile]').count();
await p.locator('[data-testid=upload-tile]').first().hover();
await p.locator('[data-testid=asset-more]').first().click();
await shot('24-upload-menu');
await p.click('[data-testid=asset-delete]');
await p.waitForTimeout(400);
console.log('upload tiles', n0, '->', await p.locator('[data-testid=upload-tile]').count());
console.log('ERRORS', JSON.stringify(errs.slice(0, 10), null, 1));
await b.close();
