import { chromium } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:5400/');
await p.waitForFunction(() => window.cream?.app.getState().ready);
const id = await p.evaluate(() => window.cream.app.getState().createDesign({ preset: 'presentation' }).id);
await p.evaluate((id) => (location.hash = '#/design/' + id), id);
await p.waitForSelector('[data-testid=editor]');
await p.waitForTimeout(1500);
await p.screenshot({ path: out + '/core-layout1.png' });
await p.click('[data-testid=tab-elements]');
await p.waitForTimeout(800);
await p.click('[data-testid=tab-design]');
await p.waitForTimeout(1500);
await p.screenshot({ path: out + '/core-layout2.png' });
console.log(await p.evaluate(() => { const s = document.querySelector('.canvas-scroll'); return { cw: s.clientWidth, sw: s.scrollWidth }; }), errs);
await b.close();
