import { chromium } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.setDefaultTimeout(20000);
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:5400/');
await p.waitForFunction(() => window.cream?.app.getState().ready);
const id = await p.evaluate(() => window.cream.app.getState().createDesign({ preset: 'instagram-square' }).id);
await p.goto('http://localhost:5400/#/design/' + id);
await p.waitForSelector('[data-testid=editor]');
await p.waitForTimeout(800);
await p.evaluate(() => window.cream.editor.setState({ side: null }));
const imgId = await p.evaluate(async () => {
  const D = await import('/src/model/defaults.ts');
  const c = document.createElement('canvas'); c.width = 400; c.height = 300; const g = c.getContext('2d');
  g.fillStyle = '#4ecdc4'; g.fillRect(0,0,400,300); g.fillStyle='#ff6b6b'; g.fillRect(150,100,80,80);
  const img = D.makeImage(c.toDataURL('image/png'), 400, 300, 60, 60, 600);
  window.cream.editor.getState().addElements([img]);
  return img.id;
});
await p.waitForTimeout(300);
await p.click('[data-testid=tb-edit-image]');
await p.click('[data-testid=tool-erase]');
const pad = await p.locator('[data-testid=erase-pad]').boundingBox();
await p.mouse.move(pad.x + pad.width * 0.45, pad.y + pad.height * 0.45); await p.mouse.down();
await p.mouse.move(pad.x + pad.width * 0.55, pad.y + pad.height * 0.55, { steps: 6 }); await p.mouse.up();
await p.screenshot({ path: out + '/x1-erase-pad.png' });
await p.click('[data-testid=magic-erase-run]');
await p.waitForFunction((i) => { const e = window.cream.editor.getState().design.pages[0].elements.find(x => x.id === i); return e.src.startsWith('asset:'); }, imgId);
await p.waitForTimeout(500);
await p.screenshot({ path: out + '/x2-erased.png' });
await p.click('[data-testid=tool-expand]'); await p.click('text=1:1'); await p.click('[data-testid=magic-expand-run]');
await p.waitForFunction((i) => { const e = window.cream.editor.getState().design.pages[0].elements.find(x => x.id === i); return Math.abs(e.naturalW - e.naturalH) < 2; }, imgId);
await p.waitForTimeout(500);
await p.screenshot({ path: out + '/x3-expanded.png' });
console.log('ok', JSON.stringify(await p.evaluate((i) => { const e = window.cream.editor.getState().design.pages[0].elements.find(x => x.id === i); return [e.naturalW, e.naturalH, Math.round(e.w), Math.round(e.h)]; }, imgId)));
console.log('ERRORS', JSON.stringify(errs));
await b.close();
