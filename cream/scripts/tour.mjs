import { chromium } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:5400/');
await p.waitForFunction(() => window.cream?.app.getState().ready);
await p.waitForTimeout(2500);
await p.screenshot({ path: out + '/tour-home.png' });
// open a template in editor
await p.evaluate(() => (location.hash = '#/templates'));
await p.waitForSelector('[data-testid=template-card]');
await p.waitForTimeout(2500);
await p.screenshot({ path: out + '/tour-templates.png' });
await p.getByTestId('template-card').nth(2).click();
await p.getByTestId('customize-template').click();
await p.waitForSelector('[data-testid=editor]');
await p.waitForTimeout(3000);
const first = p.locator('.page-frame').first().locator('[data-el-id]').nth(1);
const bb = await first.boundingBox();
if (bb) await p.mouse.click(bb.x + bb.width / 2, bb.y + bb.height / 2);
await p.waitForTimeout(800);
await p.screenshot({ path: out + '/tour-editor.png' });
await p.getByTestId('tab-elements').click();
await p.waitForTimeout(3500);
await p.screenshot({ path: out + '/tour-elements.png' });
console.log('ERR', errs);
await b.close();
