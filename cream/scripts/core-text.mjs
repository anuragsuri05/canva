import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:5400/');
await p.waitForFunction(() => window.cream?.app.getState().ready);
const id = await p.evaluate(() => window.cream.app.getState().createDesign({ preset: 'instagram-square' }).id);
await p.evaluate((id) => (location.hash = '#/design/' + id), id);
await p.waitForSelector('[data-testid=editor]');
await p.evaluate(() => document.querySelector('vite-error-overlay')?.remove());
await p.keyboard.press('t');
await p.waitForTimeout(400);
const bx = await p.locator('.page-frame [data-el-id]').last().boundingBox();
await p.mouse.dblclick(bx.x + bx.width / 2, bx.y + bx.height / 2);
await p.keyboard.type('Hi!');
await p.mouse.click(700, 300);
await p.waitForTimeout(400);
const txt = await p.evaluate(() => document.querySelector('.page-frame [data-el-id]:last-child')?.textContent);
console.log('TEXT:', JSON.stringify(txt), 'ERR', errs);
await b.close();
