import { launch, makeRichDesign } from './export-fixture.mjs';
const out = process.argv[2];
const { b, ctx, p, errs } = await launch();
const id = await makeRichDesign(p);
const log = (...a) => console.log(...a);
await p.goto('http://localhost:5400/#/present/' + id + '/full');
await p.waitForSelector('[data-testid=present-root]');
await p.waitForTimeout(1500);
await p.screenshot({ path: out + '/present-1.png' });
log('count', await p.textContent('[data-testid=present-count]'));
await p.keyboard.press('ArrowRight');
await p.waitForTimeout(280);
await p.screenshot({ path: out + '/present-trans.png' });
await p.waitForTimeout(1200);
log('count after next', await p.textContent('[data-testid=present-count]'));
await p.screenshot({ path: out + '/present-2.png' });
await p.keyboard.press('ArrowRight');
await p.waitForTimeout(250);
await p.screenshot({ path: out + '/present-circle.png' });
await p.waitForTimeout(800);
await p.keyboard.press('ArrowLeft');
await p.waitForTimeout(900);
log('count after prev', await p.textContent('[data-testid=present-count]'));
await p.keyboard.press('c');
await p.waitForTimeout(700);
await p.screenshot({ path: out + '/present-confetti.png' });
await p.keyboard.press('3');
await p.keyboard.press('d');
await p.waitForTimeout(600);
await p.screenshot({ path: out + '/present-drum.png' });
log('fx', await p.evaluate(() => ['fx-confetti', 'fx-countdown', 'fx-drumroll'].map((t) => !!document.querySelector(`[data-testid=${t}]`))));
await p.keyboard.press('x');
await p.keyboard.press('u');
await p.waitForTimeout(2000);
await p.screenshot({ path: out + '/present-curtain.png' });
await p.keyboard.press('x');
await p.keyboard.press('End');
await p.waitForTimeout(800);
log('count End', await p.textContent('[data-testid=present-count]'));
await p.mouse.move(700, 450);
await p.click('[data-testid=present-magic]');
await p.waitForTimeout(300);
await p.screenshot({ path: out + '/present-menu.png' });
await p.keyboard.press('Escape');
await p.waitForTimeout(800);
log('after esc hash', await p.evaluate(() => location.hash));
// autoplay
await p.goto('http://localhost:5400/#/present/' + id + '/autoplay');
await p.waitForSelector('[data-testid=present-root]');
await p.waitForTimeout(2600);
log('autoplay count after 2.6s', await p.textContent('[data-testid=present-count]'));
// presenter
await p.goto('http://localhost:5400/#/view/__boot');
const popupP = ctx.waitForEvent('page');
await p.goto('http://localhost:5400/#/present/' + id + '/presenter');
const aud = await popupP;
await aud.waitForSelector('[data-testid=present-root]');
await p.waitForSelector('[data-testid=presenter-root]');
await p.waitForTimeout(1000);
await p.click('[data-testid=presenter-next]');
await p.waitForTimeout(1200);
log('presenter count', await p.textContent('[data-testid=presenter-count]'), 'audience count', await aud.textContent('[data-testid=present-count]'));
await p.click('[data-testid=notes-larger]');
await p.screenshot({ path: out + '/presenter.png' });
await aud.screenshot({ path: out + '/audience.png' });
// audience navigates back -> presenter follows
await aud.keyboard.press('ArrowLeft');
await p.waitForTimeout(800);
log('after audience prev presenter', await p.textContent('[data-testid=presenter-count]'));
await p.click('[data-testid=presenter-exit]');
await p.waitForTimeout(500);
log('ERRORS', JSON.stringify(errs.slice(0, 10)));
await b.close();
